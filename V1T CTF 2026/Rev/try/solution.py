def u32(x):
    return x & 0xffffffff

def rol8(x, r):
    x &= 0xff
    r &= 7
    return x if r == 0 else ((x << r) & 0xff) | (x >> (8 - r))

def ror8(x, r):
    x &= 0xff
    r &= 7
    return x if r == 0 else (x >> r) | ((x << (8 - r)) & 0xff)

def mix(i, key):
    t = u32(u32(0x9e3779b9 * i) ^ u32(73244475 * key) ^ 0x6d2b79f5)
    v3 = u32(2146121005 * u32((t >> 16) ^ t))
    p = u32(0x847ca68b * u32((v3 >> 15) ^ v3))
    v4 = u32((p >> 16) ^ p)
    return ((v4 >> 24) ^ (v4 >> 16) ^ (v4 >> 8) ^ v4) & 0xff

def pair(a, b, i, j, seed):
    v1 = rol8((((j + seed) & 0xff) ^ b) + (((i + seed) & 0xff) ^ a), (j ^ i ^ seed) & 7)
    v2 = rol8(((((seed >> 3) & 6) | 1) * b + ((seed & 6) | 1) * a) & 0xff, (seed + j + i) & 7)
    return (v1 ^ v2) & 0xff

